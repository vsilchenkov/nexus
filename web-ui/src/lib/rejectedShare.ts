import { TEAM_PARAM } from "./teamShare";

// §98.3: ссылка на КОНКРЕТНЫЙ отказ — «вот этот отказ и его запросы».
//
// До §98 карточка отказа открывалась локальным состоянием и адреса не имела:
// переслать коллеге разбор было нечем, приходилось описывать словами, какую
// строку открыть. Тот же урок, что §79.3 для вкладок узла.
//
// Формат ссылки описан здесь ОДИН раз (правило §89.3): иначе адрес, который
// пишет экран, и адрес, который кладёт в буфер кнопка, однажды разойдутся — и
// разойдутся молча.

// REJECTED_PARAM — id открытой карточки в адресной строке.
export const REJECTED_PARAM = "rejected";

// rejectedPath — маршрут журнала отказов. Не экспортируется: наружу нужен
// только собранный адрес, а второй способ его собрать однажды разойдётся с этим.
const rejectedPath = "/logs/rejected";

/**
 * rejectedPageUrl — абсолютная ссылка на карточку отказа для кнопки
 * «Поделиться».
 *
 * teamSlug обязателен: карточка читается team-scoped эндпоинтом
 * (`GET /api/rejected/:id`), и без переключения команды получатель ссылки
 * увидел бы «не найдено» вместо отказа. Параметр применяет общий механизм §76
 * (useTeamUrlParam), маршрут для этого внесён в его белый список.
 *
 * Origin берётся из адреса текущего окна — как в nodePageUrl (§58).
 */
export function rejectedPageUrl(id: string, teamSlug: string): string {
  const q = new URLSearchParams({ [REJECTED_PARAM]: id });
  if (teamSlug) q.set(TEAM_PARAM, teamSlug);
  return `${window.location.origin}${rejectedPath}?${q.toString()}`;
}
