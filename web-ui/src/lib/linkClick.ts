import { type MouseEvent } from "react";

// §89.3: разбор клика по элементу, который ОДНОВРЕМЕННО настоящая ссылка (href
// ради браузера: контекстное меню «Открыть в новой вкладке», Ctrl/Cmd+клик,
// средняя кнопка) и носитель побочного эффекта (смена команды сессии).

// isPlainLeftClick — «обычный» левый клик, который приложение обрабатывает само.
// Всё остальное (средняя кнопка, Ctrl/Cmd/Shift/Alt) — просьба браузера открыть
// href по-своему, в новой вкладке или окне; побочка в таком клике срабатывать НЕ
// должна: она изменила бы ТЕКУЩУЮ вкладку, которую пользователь трогать не
// просил.
//
// Навигацию это не ломает: react-router проверяет ровно то же условие у себя
// (shouldProcessLinkClick) и модифицированный клик не перехватывает — достаточно
// выйти из обработчика и отдать событие браузеру. Средняя кнопка в современных
// браузерах вообще не даёт click (только auxclick), проверка e.button — про
// старые Firefox.
export function isPlainLeftClick(e: MouseEvent): boolean {
  return e.button === 0 && !e.metaKey && !e.ctrlKey && !e.shiftKey && !e.altKey;
}
