// Состояние интерфейса, принадлежащее пользователю, а не вкладке (§104.8).
//
// Зеркала в sessionStorage живут столько же, сколько вкладка, и о смене
// пользователя ничего не знают: выход и вход другим логином в той же вкладке
// отдавали ему фильтры рабочего стола (§54), строку глобального поиска (§62) и
// сквозной режим «Все команды» (§86) прежнего пользователя.
//
// Настройки браузера в localStorage (тема, вид таблицы, автообновление,
// свёрнутые группы) сюда не входят: это выбор того, кто сидит за машиной, а не
// данные сессии.
import { clearFilters } from "./overviewFilters";
import { saveGlobalSearchQ } from "./searchHistory";
import { resetTeamScope } from "./teamScope";

// resetUserSessionState — сбросить состояние интерфейса прежней сессии.
//
// Зовёт страница входа при монтировании: через неё проходит любой конец
// сессии — выход (переход без перезагрузки), 401 (перезагрузка на /login) и
// ручной заход на /login. Сквозной режим держит копию и в памяти модуля, её
// сбрасывает resetTeamScope: после выхода без перезагрузки одного хранилища
// было бы мало.
export function resetUserSessionState(): void {
  clearFilters();
  saveGlobalSearchQ(""); // пустая строка удаляет ключ
  resetTeamScope();
}
