// §98.7: чем маскируется поле секрета — CSS или типом поля.
//
// Менеджер паролей Chrome/Edge опознаёт поле по `type="password"`, а не по
// `autocomplete`: атрибут `new-password` лишь меняет предложение с «подставить»
// на «сгенерировать», а попап с личными учётками пользователя всплывает всё
// равно. Поверх поля «Пароль» узла это не только мешает — на правке узла пустое
// поле означает «оставить старый секрет» (§5.5), и незамеченная подстановка
// чужого пароля затирает рабочие креды узла.
//
// Поэтому секрет ЧУЖОЙ системы маскируется CSS'ом на обычном текстовом поле:
// полем пароля браузер его не считает, ни подставлять, ни предлагать сохранить
// не пытается.

/**
 * secretMaskSupported — умеет ли браузер маскировать текст через
 * `-webkit-text-security`.
 *
 * Поддержан Chrome, Edge, Safari и Firefox 119+. Где нет — вызывающая сторона
 * обязана вернуться к `type="password"`: показать секрет открытым текстом
 * нельзя ни при каких обстоятельствах, и «не смогли замаскировать» это не
 * повод, а запрет.
 *
 * Отсутствие самого CSS.supports (старый движок, jsdom в тестах) трактуется как
 * «не поддержано» — деградация в сегодняшнее поведение, а не в открытый текст.
 *
 * Без кеша намеренно: вызов дешёвый, полей секретов на экране единицы, а
 * кеш потребовал бы точки сброса ради тестов — то есть тестового хука в
 * продакшн-коде.
 */
export function secretMaskSupported(): boolean {
  const css = (globalThis as { CSS?: { supports?: (prop: string, value: string) => boolean } }).CSS;
  return typeof css?.supports === "function" && css.supports("-webkit-text-security", "disc");
}

// SECRET_MASK_CLASS — класс из styles/globals.css, включающий маскировку.
export const SECRET_MASK_CLASS = "secret-mask";

/**
 * PASSWORD_MANAGER_OFF — атрибуты, которыми поле объявляется «не для менеджера
 * паролей» (§98.7).
 *
 * Вынесено отдельно от SecretInput, потому что нужно и СОСЕДНЕМУ полю логина:
 * менеджер ищет ПАРУ «логин + пароль», и без пометки на первом поле он всё
 * равно предложит подставить туда чужую учётку. Набор тот же, что в §90.3 у
 * полей поиска: `autocomplete` уважают Firefox и Safari, `data-*` — сторонние
 * менеджеры (1Password, LastPass, Dashlane) со своей эвристикой.
 *
 * Имя поля сюда НЕ входит: у секрета оно нейтральное («secret»), а у логина
 * любое осмысленное имя само служит эвристике подсказкой, поэтому там его
 * лучше не задавать вовсе.
 */
export const PASSWORD_MANAGER_OFF = {
  autoComplete: "off",
  "data-1p-ignore": true,
  "data-lpignore": "true",
  "data-form-type": "other",
} as const;
