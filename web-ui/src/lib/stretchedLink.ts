// Растянутая ссылка: строка или карточка кликается целиком, оставаясь при этом
// НАСТОЯЩЕЙ ссылкой.
//
// Зачем. §7.3 обещает «клик по строке таблицы или по карточке открывает узел»,
// но ссылка занимает ровно ширину своей надписи: на бою это 135 px из 1033 px
// строки и 158 px из ~400 px карточки. Оператор целится в карточку, попадает в
// пустоту и решает, что интерфейс сломан (правая кнопка при этом работает —
// она попадает точно по надписи, и «Открыть в новой вкладке» открывает узел).
//
// Приём — псевдоэлемент ссылки, растянутый по контейнеру. Обработчик клика на
// строке решил бы задачу зоны, но сломал бы природу элемента: Ctrl+клик,
// средняя кнопка и «Открыть в новой вкладке» перестали бы работать (урок §79.3,
// повторно пойманный в §89.3 и §98.2).
//
// Контракт из ТРЁХ участников — забыть любого значит получить молчаливую
// поломку, поэтому все три имени приходят одним импортом:
//
//   STRETCH_HOST   — контейнер, который ссылка обязана накрыть (<tr>, <Card>).
//   STRETCHED_LINK — сама ссылка.
//   ABOVE_STRETCH  — всё, что обязано сохранить СВОИ клики, hover и подсказки.
//
// Классы — литеральные строки: Tailwind сканирует исходники и не видит имён,
// собранных конкатенацией или интерполяцией. Класс, собранный из кусков, попадёт
// в разметку, но не в стили — самый дорогой вид поломки.

// STRETCH_HOST — опора для псевдоэлемента.
//
// Ставится на САМЫЙ внешний контейнер зоны. Если поставить его на промежуточный
// элемент (например, на <td> вместо <tr>), зона схлопнется до него — то есть
// вернётся ровно тот дефект, ради которого приём и вводится.
export const STRETCH_HOST = "relative";

// STRETCHED_LINK — ссылка, накрывающая STRETCH_HOST целиком.
export const STRETCHED_LINK = "after:absolute after:inset-0 after:content-['']";

// ABOVE_STRETCH — поднять элемент над растянутой ссылкой.
//
// Нужен НЕ только кликабельным элементам: псевдоэлемент перехватывает ещё
// hover, подсказки (title) и выделение текста. Под ссылкой оказываются немыми
// и кнопки, и тултипы.
//
// ВАЖНО: stopPropagation здесь не помогает и помочь не может. Он спасает, когда
// обработчик висит на предке и событие всплывает; растянутая ссылка перехватывает
// клик ДО цели — накрытый элемент события не получает вовсе, останавливать
// нечего. Единственное лекарство — поднять элемент этим классом.
//
// relative обязателен: z-index без position не действует.
export const ABOVE_STRETCH = "relative z-10";
