// §98.1: какая подсказка стоит в пустом поле секрета на форме узла.
//
// Сам секрет бэкенд наружу не отдаёт никогда (§5.5) — приходят только флаги
// `*_set`. До §98 подсказка была одна на все случаи («оставьте пустым, чтобы не
// менять»), и по форме нельзя было понять, настроена авторизация узла или нет:
// у узла с паролем и у узла без пароля поле выглядело одинаково.
//
// Решение вынесено из компонента отдельным модулем ровно затем, чтобы его
// можно было проверить таблицей: правило нетривиально из-за гейта по типу
// авторизации, а в JSX оно повторяется пять раз.

// Ключи перевода подсказки. Строкой, а не enum'ом: значения уходят прямо в
// t() и обязаны совпадать с locales/*.json.
export const SECRET_SET_KEY = "node.form.secret_set";
export const SECRET_KEEP_KEY = "node.form.keep_secret";

/**
 * secretPlaceholderKey — ключ подсказки для поля секрета, либо null.
 *
 * null означает «подсказка этого модуля не нужна»: узел создаётся, секрета ещё
 * нет и никакого «оставить старое» не существует. Что показать в этом случае —
 * решает вызывающая сторона (пусто у кредов узла, "password" у RabbitMQ).
 *
 * typeUnchanged — гейт, без которого подсказка врёт. Флаг `*_set` относится к
 * СТРОКЕ кредов, а не к типу авторизации: у узла с `auth_type=token` он
 * останется true и после переключения формы на `basic`, но лежит там токен, а
 * не пара «логин:пароль». «Установлен» в поле пароля был бы не просто
 * неточностью — оператор оставил бы поле пустым, сервер по контракту Update
 * сохранил бы СТАРЫЙ токен (§5.5), и узел молча остался бы с прежней
 * авторизацией.
 */
export function secretPlaceholderKey(o: {
  isNew: boolean;
  isSet: boolean | undefined;
  typeUnchanged: boolean;
}): string | null {
  if (o.isNew) return null;
  return o.isSet && o.typeUnchanged ? SECRET_SET_KEY : SECRET_KEEP_KEY;
}
