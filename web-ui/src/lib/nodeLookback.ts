import { type Node } from "../api/client";

// §84.4: чем считается пустое «от» в произвольном периоде.
//
// Ответ «началом доступных данных» — не абстракция: записей старше глубины
// хранения физически нет, их удалил TTL. Поэтому нижняя граница берётся из
// самого узла и всегда материализуется в конкретный момент времени — сужение
// по колонке партиционирования (§72.4) остаётся единственным, что держит
// стоимость запроса на боевых таблицах.

// MAX_LOOKBACK_MS_DEFAULT — потолок там, где глубина хранения неизвестна:
// внешние таблицы §64 (ретенцией владеет не Nexus), рабочий стол со многими
// узлами, мониторинг Kafka. 30 суток — самый крупный пресет периода.
export const MAX_LOOKBACK_MS_DEFAULT = 30 * 24 * 3600_000;

/**
 * nodeLookbackMs — глубина хранения узла в миллисекундах.
 *
 * Внешняя таблица (§64) даёт потолок по умолчанию: её ретенцией управляет
 * оператор, а не Nexus, и `clickhouse_retention_days` узла её не описывает —
 * подставлять оттуда число значило бы соврать о доступной глубине.
 */
export function nodeLookbackMs(node: Pick<Node, "external_table" | "clickhouse_retention_days">): number {
  const days = node.clickhouse_retention_days;
  if (node.external_table || !days || days <= 0) return MAX_LOOKBACK_MS_DEFAULT;
  return days * 24 * 3600_000;
}
