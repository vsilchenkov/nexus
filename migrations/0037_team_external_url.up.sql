-- 0037_team_external_url.up.sql
--
-- §89.4 (внешняя ссылка команды): адрес, по которому узлы команды доступны
-- СНАРУЖИ контура. Внешние системы часто ходят не в Nexus напрямую, а через
-- шлюз со своим адресом и своим префиксом пути; оператор знал адрес узла
-- внутри контура, но не знал, какой адрес выдавать наружу.
--
-- Значение — БАЗА: интерфейс дописывает к ней путь узла и показывает результат
-- третьей строкой в блоке «Полный адрес» конфига узла. Маршрутизации колонка не
-- касается вообще — Receiver её не читает, это справочные данные.
--
-- NOT NULL DEFAULT '' — как comment у узла (0016) и external_table (0027):
-- проще в Go (без указателей), «не задана» и «пустая» здесь одно и то же.
-- VARCHAR(2048) совпадает с лимитом target_url узла и с
-- domain.MaxTeamExternalURLLen.
--
-- CHECK на формат НЕ ставится намеренно: проверка «абсолютный http(s) без
-- query» живёт в domain.ValidateTeamExternalURL, и повторять её регулярным
-- выражением в SQL значило бы завести второй источник истины, который разъедется
-- при первой же правке правила (в отличие от teams_slug_format, где регэксп
-- простой и зафиксирован в ТЗ).
ALTER TABLE teams ADD COLUMN external_url VARCHAR(2048) NOT NULL DEFAULT '';
