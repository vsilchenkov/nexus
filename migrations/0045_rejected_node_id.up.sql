--
-- §117 ТЗ: узел, к которому относится отказ (узел выключен, метод запрещён,
-- нет авторизации, адрес запрещён…). По нему «Логи → Отказы» ведут на страницу
-- узла.
--
-- Узел фиксирует Receiver в момент отказа, а не Web на чтении: путь группы —
-- это путь АДРЕСА (§94.3), и у хвоста passthrough-адреса (§39), legacy-адреса
-- («чтение B») и переименованного узла он с путём узла не совпадает.
--
-- NULL — отказ до резолва (узла нет, лимит частоты, пустой путь) или группа,
-- накопленная до §117 и с тех пор не повторявшаяся. Внешнего ключа нет
-- намеренно: узел удаляют, а его отказы остаются в журнале до срока хранения;
-- Web показывает такие группы как «узел удалён». В естественный ключ группы
-- колонка не входит.
--
-- Миграция аддитивная (§74.2): старый Receiver колонку не пишет, старый Web её
-- не читает.
ALTER TABLE rejected_groups ADD COLUMN IF NOT EXISTS node_id UUID;
