-- 0044_rejected_mask_bot_tokens.up.sql
--
-- §117.7 ТЗ: журнал отказов (§94) писал путь адреса как пришёл, и у
-- passthrough-узла Telegram (§39) секрет токена бота `bot<id>:<secret>` оседал
-- в rejected_groups.node_path и rejected_samples.raw_path — то есть в
-- интерфейсе «Отказов» и CSV-выгрузке у любого оператора. Код с §117 маскирует
-- его до записи (`bot<id>:***`, sensitive.MaskBotTokens); здесь вычищается
-- накопленное.
--
-- Удаление, а не UPDATE с маскированием: путь входит в естественный ключ
-- группы (rejected_groups_key), и две группы одного бота с разными секретами
-- (ротация токена) после маскирования совпали бы — UPDATE упал бы на
-- уникальности. Журнал оперативный и со сроком хранения (§94.5): группы
-- пересоберутся из следующих отказов уже с маской.
--
-- Шаблон повторяет sensitive.MaskBotTokens: `bot` в любом регистре, цифры
-- номера, двоеточие, не меньше 20 символов base64url. Маска `***` под него не
-- подходит — повторный прогон ничего не удаляет.
--
-- ВНИМАНИЕ: необратимо. Клиенты и сэмплы удалённых групп уходят каскадом;
-- down-миграция их не восстанавливает (строка «Откат» в CHANGELOG, §74.6).
DELETE FROM rejected_groups WHERE node_path ~* 'bot[0-9]+:[a-z0-9_-]{20,}';

-- Сэмпл с секретом у группы без секрета в пути: путь группы и путь сэмпла
-- разбираются из одного адреса, но страховка дешёвая.
DELETE FROM rejected_samples WHERE raw_path ~* 'bot[0-9]+:[a-z0-9_-]{20,}';
