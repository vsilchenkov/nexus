-- ПОТЕРЯ ДАННЫХ: удаляются справочник групп и привязки узлов к группам
-- (nodes.group_id). Сами узлы и их настройки не затрагиваются — группа была
-- только UI-метаданными и в маршрутизации не участвовала. После возврата на
-- прежнюю версию кода экран «Узлы» показывает плоский список, поэтому
-- функционального смысла хранить колонку и таблицу нет; при повторном накате
-- группы придётся завести и расставить заново. rollback_info.py пометит потерю
-- сам (DROP TABLE / DROP COLUMN).
--
-- Порядок обязателен: сначала колонка со ссылкой, потом таблица, иначе DROP
-- TABLE упрётся в внешний ключ.

ALTER TABLE nodes DROP COLUMN IF EXISTS group_id;

DROP TABLE IF EXISTS node_groups;
