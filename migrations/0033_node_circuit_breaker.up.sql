-- 0033_node_circuit_breaker.up.sql
--
-- §81.3 (политика circuit breaker'а настраивается): порог отказов и пауза до
-- половинчато-открытой пробы перестают быть литералами в коде.
--
-- NULL = «брать глобальное значение из конфигурации»
-- (sender.circuit_breaker.threshold / cooldown_sec). Именно NULL, а не 0:
-- ноль — это осмысленное значение для многих числовых настроек узла, и
-- отличить «не задано» от «задано нулём» иначе было бы нельзя.
--
-- Зачем per-node. У узла с 200-миллисекундным приёмником и у узла, где ответ
-- штатно идёт 20 секунд, разная норма отказов: общий порог 5/30 с для второго
-- означает, что пять таймаутов подряд уводят весь его поток в DLQ, хотя
-- приёмник жив и просто медленный (боевой разбор §80.5).
--
-- Аддитивно (контракт схемы §74.2): колонки добавляются со значением по
-- умолчанию NULL, старый код их не читает и работает по глобальной политике.
ALTER TABLE nodes ADD COLUMN circuit_breaker_threshold INTEGER;
ALTER TABLE nodes ADD COLUMN circuit_breaker_cooldown_sec INTEGER;
