-- 0030_instance_ch_claimed.up.sql
--
-- §70.5: признак «эта нода уже успешно захватывала свои БД в ClickHouse».
--
-- Гейт первого запуска изначально опирался на «в PostgreSQL ещё нет узлов»
-- (FreshPG). На стенде это оказалось неверным признаком: у только что
-- развёрнутой ноды узлов нет и на втором старте — гейт срабатывал на её
-- СОБСТВЕННУЮ базу, и нода становилась незапускаемой до создания первого узла.
--
-- Флаг ставится после первого успешного захвата и снимает гейт со следующего
-- старта. Проверка чужого маркера при этом остаётся в силе всегда.
ALTER TABLE instance_identity
    ADD COLUMN IF NOT EXISTS ch_claimed BOOLEAN NOT NULL DEFAULT false;
