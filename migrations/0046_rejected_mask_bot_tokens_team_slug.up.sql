-- §117.7 ТЗ, дополнение к 0044 (найдено ревизией перед выпуском 1.42.0).
-- Код до §117 резал путь отказа на слог команды и путь узла БЕЗ маскирования,
-- поэтому токен бота в ПЕРВОМ сегменте адреса оседал не в node_path, а в
-- team_slug: `POST /api/v1/request/bot<id>:<secret>/sendMessage` (SDK Telegram,
-- нацеленный на корень шины) давал группу team_slug='bot<id>:<secret>',
-- node_path='sendMessage'. Слог режется до 64 символов, токен (~45–50) влезает
-- целиком. 0044 чистит только node_path, и такая группа оставалась видна
-- администратору в «Отказах» («команда не опознана») и в колонке team_slug CSV.
--
-- Новая миграция, а не правка 0044: та уже применена на стендах. Шаблон тот же,
-- что в 0044 и sensitive.MaskBotTokens; маска `***` под него не подходит —
-- повторный прогон ничего не удаляет. Клиенты и сэмплы уходят каскадом (DDL
-- 0040); сэмплы с секретом в raw_path 0044 уже удалила.
--
-- ВНИМАНИЕ: необратимо, как и 0044 (строка «Откат» в CHANGELOG, §74.6).
DELETE FROM rejected_groups WHERE team_slug ~* 'bot[0-9]+:[a-z0-9_-]{20,}';
