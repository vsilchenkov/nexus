-- 0034_node_async_ack_spec.up.sql
--
-- §83 (шаблон ответа приёма): узел описывает, чем Receiver отвечает клиенту на
-- успешный приём запроса в очередь, вместо жёсткого {"result":true,"id":…}.
--
-- Зачем. Клиенты с курсором (СКУД Sigur и любой источник, двигающий указатель
-- по эхо-подтверждению) не понимают ответ шины и шлют один и тот же пакет
-- бесконечно. Боевой разбор — §82.3, где это следствие было зафиксировано, но
-- отбить его настройкой узла было нечем.
--
-- NULL = «отвечать как раньше». Именно NULL, а не пустой объект: спека без
-- шаблона бессмысленна, и отличать «не настроено» от «настроено пусто» не
-- нужно, а nil в домене даёт прежнее поведение без единой ветки в коде.
--
-- JSONB, а не набор плоских колонок: язык подстановок и структура спеки будут
-- дозревать (условия, несколько правил), и каждая доработка не должна стоить
-- миграции. Прецедент — ch_templates.spec (§19).
--
-- Аддитивно (контракт схемы §74.2): колонка добавляется как NULL, старый код
-- её не читает. Откат кода без отката схемы безопасен.
ALTER TABLE nodes ADD COLUMN async_ack_spec JSONB;

-- Второй рубеж после domain.Node.Validate: в колонку пишет только Web, но
-- ручная правка SQL на бою не должна оставлять узел, на котором Receiver
-- споткнётся при разборе. jsonb_typeof/octet_length доступны с PG 9.4 —
-- боевой сервер на PostgreSQL 12 их принимает (см. 0032, правило про PG13+).
ALTER TABLE nodes ADD CONSTRAINT nodes_async_ack_spec_object
    CHECK (async_ack_spec IS NULL OR jsonb_typeof(async_ack_spec) = 'object');

-- 16 КиБ — вдвое больше потолка шаблона (ackspec.MaxTemplateBytes = 8 КиБ) с
-- запасом на остальные поля спеки. Тело ответа собирается в память Receiver'а
-- на каждый принятый запрос, поэтому размер ограничен на уровне хранилища тоже.
ALTER TABLE nodes ADD CONSTRAINT nodes_async_ack_spec_size
    CHECK (async_ack_spec IS NULL OR octet_length(async_ack_spec::text) <= 16384);
