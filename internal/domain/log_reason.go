package domain

// Машинные маркеры колонки `reason` лог-таблицы (§81.2.1).
//
// Формат записи — «<маркер>: <деталь>»: префикс стабилен и пригоден для
// фильтрации и сопоставления в интерфейсе, хвост человекочитаем.
//
// Зачем маркеры вместо текста ошибки стандартной библиотеки. Сырой
// `err.Error()` от net/http выглядит как
// `Post "https://host/path": context canceled` — он нестабилен (менять его
// может обновление Go), его нельзя сопоставить в UI, и он **тащит полный
// адрес**: у узлов с динамическим режимом URL хвост собран из входящего
// запроса, то есть кусок входа утекает в журнал — тот же класс утечки, что
// нашла ревизия §68.
//
// Нормализуются только два исхода: уход вызывающей стороны и собственный
// таймаут узла. Тексты остальных сетевых ошибок (`connection refused`, DNS,
// TLS) остаются сырыми — они не содержат входных данных и нужны для
// диагностики адреса; общая санитизация текстов stdlib в §81 не входит.
//
// Константы живут в domain, потому что нужны обеим сторонам: Sender их пишет,
// Web по ним фильтрует (§81.5) и помечает строки в интерфейсе.
const (
	// ReasonCircuitBreakerOpen — запрос отбит защитой узла без сетевого вызова.
	ReasonCircuitBreakerOpen = "circuit_breaker_open"

	// ReasonClientCanceled — РОДИТЕЛЬСКИЙ КОНТЕКСТ вызова умер раньше ответа.
	// О здоровье приёмника такой исход не говорит ничего: он мог отвечать и
	// успешно — просто ответа уже никто не ждал.
	//
	// Читать как «виноват клиент» НЕЛЬЗЯ. Дискриминатор здесь один — живость
	// родительского контекста, а умереть он может не только от ухода клиента:
	//
	//   - клиент шины закрыл соединение либо его оборвал прокси перед Receiver'ом;
	//   - останавливается сам сервис (штатный shutdown);
	//   - **порвался транспорт Receiver→Sender** — например, рестарт одного из
	//     сервисов посреди долгого вызова. До §82.1 сюда же попадал обрыв по
	//     keepalive: gRPC-сервер Sender'а слал GOAWAY «too_many_pings» и закрывал
	//     соединение, а исход выглядел уходом клиента. Именно из-за этой подмены
	//     боевой разбор 06.08.2026 больше суток искал причину во внешнем фронте,
	//     хотя дефект был внутри шины.
	//
	// Отдельного маркера для обрыва транспорта нет намеренно: признак пришлось бы
	// тянуть из Receiver'а в Sender через поле gRPC-запроса — большая поверхность
	// ради случая, который после §82.1 почти не встречается. Признак обрыва
	// транспорта ищи на стороне Receiver'а: `sender.Send` возвращает
	// `codes.Unavailable`, тогда как уход клиента даёт `codes.Canceled`.
	ReasonClientCanceled = "client_canceled"

	// ReasonUpstreamTimeout — истёк собственный таймаут узла (`timeout_ms`).
	// В отличие от предыдущего это счёт к приёмнику: он не уложился в срок.
	ReasonUpstreamTimeout = "upstream_timeout"
)

// Состояния circuit breaker'а узла для представления наружу (§81.4).
// Кодировка совпадает с той, что хранит platform/circuitbreaker: одна строка на
// весь путь «Sender записал → Web показал», без перевода в промежуточных слоях.
const (
	BreakerStateClosed   = "closed"
	BreakerStateOpen     = "open"
	BreakerStateHalfOpen = "half_open"
)
