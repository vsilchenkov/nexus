package domain

// HeaderNexusID — заголовок с ID записи лога доставки (§118.7).
//
// Sender ставит его в каждый исходящий запрос к получателю: значение одинаково
// на всех повторах одного сообщения (in-process ретраи, DLQ-репроцессор,
// передоставка Kafka), поэтому получатель может по нему дедуплицировать. Тот же
// заголовок Receiver отдаёт клиенту в ответе по шаблону §83 — один ID проходит
// путь «клиент → шина → получатель».
//
// Имя намеренно НЕ Idempotency-Key: с ним net/http считает POST повторяемым и
// сам переотправляет его на переиспользованном соединении уже после отправки —
// для получателя, который ключ не понимает, это лишний источник повторов.
const HeaderNexusID = "X-Nexus-Id"
