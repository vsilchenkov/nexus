package pg

// FreshInstanceSQL — SQL-выражение «экземпляр чистый»: в базе нет узлов и нет
// команд, кроме сидированной миграцией 0008. Возвращает одно boolean-значение.
//
// Единственный источник признака для всех, кто его проверяет: гейт первого
// запуска §70.5 (bootstrap), карточка «Резервная копия» и транзакция импорта
// конфигурации §110. Разойдись они — вкладка показала бы «можно
// восстанавливать», а импорт отказал бы (или хуже — наоборот).
//
// Признак «команд ≤ 1» опирается на то, что сидированная Default удалению не
// подлежит: любая команда сверх неё создана оператором, и экземпляр уже рабочий.
const FreshInstanceSQL = `
SELECT (SELECT count(*) FROM nodes) = 0
   AND (SELECT count(*) FROM teams) <= 1`
