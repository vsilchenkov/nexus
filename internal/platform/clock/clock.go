// Package clock — источник текущего времени как зависимость (§4 CLAUDE.md).
//
// Зачем: прямой time.Now() в бизнес-логике делает поведение непроверяемым там,
// где время влияет на РЕШЕНИЕ — истёк ли токен, какие записи считать
// устаревшими, какое окно показать. Тест на такую логику приходится либо
// пропускать, либо подгонять под реальные часы (sleep, «примерно сейчас»).
//
// Что НЕ надо переводить на Clock:
//   - замеры длительности (start := time.Now(); ... time.Since(start)) —
//     это измерение, а не решение, и подмена часов там ничего не проверяет;
//   - штампы created_at/updated_at, которые уходят в БД и логи как факт момента.
//
// До этого пакета в проекте жили три несовместимых самоделки (интерфейс в
// nodecache, опция WithOwnerClock в clickhouse, поле now func() в
// dlq_reprocess/peer_instance) — теперь у них один тип.
package clock

import "time"

// Clock отдаёт текущее время. Единственный метод: всё остальное (таймеры,
// тикеры) остаётся за пакетом time — подменять их ради тестов не требовалось
// ни разу, а интерфейс из одного метода реализуется в тесте одной строкой.
type Clock interface {
	Now() time.Time
}

// systemClock — часы процесса.
type systemClock struct{}

func (systemClock) Now() time.Time { return time.Now() }

// System возвращает системные часы. Это дефолт всех конструкторов: опция
// WithClock нужна только тестам.
func System() Clock { return systemClock{} }

// Func адаптирует функцию к Clock — для мест, где время уже пробрасывалось
// как func() time.Time.
type Func func() time.Time

// Now вызывает саму функцию.
func (f Func) Now() time.Time { return f() }

// Fixed — застывшие часы: всегда возвращают t. Для тестов, где важно ровно
// одно значение («токен истёк вчера»).
func Fixed(t time.Time) Clock { return Func(func() time.Time { return t }) }
