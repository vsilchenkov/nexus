package usecase

import (
	"strings"
	"time"
)

// §79.5 «Шаг графика»: ширина одного столбца выбирается пользователем, а не
// выводится из длительности окна. Пара (окно, шаг) согласуется здесь —
// единственной чистой функцией, которую зовут и страница узла, и дашборд.

// maxChartBuckets — потолок числа столбцов. При ширине графика ~900 px это уже
// 2 px на столбец: рисовать плотнее — врать. Заодно ограничивает число групп в
// ClickHouse.
const maxChartBuckets = 400

// chartStepPresets — словарь шагов, общий с пресетами периода (§21). Значения
// вроде «7д» через time.ParseDuration не выражаются, поэтому карта своя.
var chartStepPresets = map[string]time.Duration{
	"1h":  time.Hour,
	"3h":  3 * time.Hour,
	"24h": 24 * time.Hour,
	"7d":  7 * 24 * time.Hour,
	"14d": 14 * 24 * time.Hour,
	"30d": 30 * 24 * time.Hour,
}

// chartStepLadder — человеческая лестница ширины столбца (§84.1). На неё
// снапится автоматический шаг.
//
// Отбор значений — НЕ эстетический: все они делят 86400 нацело. ClickHouse
// считает toStartOfInterval от UTC-эпохи, поэтому только делитель суток
// гарантированно кладёт границы столбцов на круглые отметки UTC-часов и
// UTC-суток. Значение вроде 225 с (то, что выдавало деление окна 3 ч на 48)
// этим свойством не обладает, и столбцы «плывут» относительно часов — а
// step_seconds уходит клиенту и определяет и подсказку, и границы выборки при
// переходе «клик по столбцу → журнал» (§33.4).
//
// Граница защиты: выравнивание держится на UTC. В зоне со смещением, кратным
// часу (МСК = UTC+3), часовые и более мелкие столбцы совпадают с местными
// часами, а суточный начинается в 03:00 МСК, а не в местную полночь.
var chartStepLadder = []time.Duration{
	time.Minute,      // 60
	5 * time.Minute,  // 300
	10 * time.Minute, // 600
	15 * time.Minute, // 900
	30 * time.Minute, // 1800
	time.Hour,        // 3600
	2 * time.Hour,    // 7200
	3 * time.Hour,    // 10800
	6 * time.Hour,    // 21600
	12 * time.Hour,   // 43200
	24 * time.Hour,   // 86400
}

// autoChartBuckets — ЦЕЛЕВАЯ плотность графика, когда шаг не задан: сколько
// столбцов хочется получить на окне такой длительности. Числа сохранены от
// §79.5 дословно.
//
// Это именно цель, а не результат: с §84.1 частное window/autoChartBuckets
// снапится вверх на chartStepLadder, поэтому фактических столбцов выходит
// столько же или МЕНЬШЕ (см. snapAutoStep).
func autoChartBuckets(window time.Duration) int {
	switch {
	case window <= time.Hour:
		return 60
	case window <= 24*time.Hour:
		return 48
	case window <= 7*24*time.Hour:
		return 84
	default:
		return 90
	}
}

// snapAutoStep — автоматический шаг: идеальная ширина столбца, поднятая до
// ближайшего круглого значения лестницы (§84.1).
//
// Снап только ВВЕРХ, и это гарантия, а не предпочтение: шаг не меньше
// идеального ⇒ столбцов не больше целевой плотности ⇒ число групп в ClickHouse
// не растёт ни на одном окне (вкладка поллится каждые ~12 с).
//
// Лестница исчерпана (окно больше ~90 суток) — продолжаем её кратными суток по
// тому же правилу «наименьшее значение ≥ идеального». Некруглого деления в
// расчёте не остаётся нигде.
//
// Окна короче минуты вырождаются в один столбец: минута — осознанный низ
// лестницы, посекундный график не несёт смысла. Дальше resolveChartStep всё
// равно сожмёт шаг до окна.
func snapAutoStep(window time.Duration) time.Duration {
	ideal := window / time.Duration(autoChartBuckets(window))
	for _, s := range chartStepLadder {
		if s >= ideal {
			return s
		}
	}
	const day = 24 * time.Hour
	return ((ideal + day - 1) / day) * day // ceil до целых суток
}

// ParseChartStep — разбор параметра шага. Пустая строка и "auto" → 0
// («выбери сам»). Кроме пресетов принимается Go-длительность (`30m`, `90s`) —
// для клиентов API, которым словаря мало. Мусор → 0, а не ошибка: график не то
// место, где стоит отвечать 400 на кривой необязательный параметр.
func ParseChartStep(s string) time.Duration {
	s = strings.TrimSpace(strings.ToLower(s))
	if s == "" || s == "auto" {
		return 0
	}
	if d, ok := chartStepPresets[s]; ok {
		return d
	}
	if d, err := time.ParseDuration(s); err == nil && d > 0 {
		return d
	}
	return 0
}

// resolveChartStep — шаг бакета (в секундах) и число столбцов для окна.
//
// Правила согласования пары (окно, шаг):
//   - шаг не задан → круглый автоматический шаг (§84.1, см. snapAutoStep);
//   - шаг больше окна → шаг сжимается до окна: ровно один столбец, а не пустой
//     график и не столбец, торчащий за границу периода;
//   - столбцов вышло больше maxChartBuckets → шаг поднимается до окно/потолок.
//
// Автоматический шаг проходит те же два ограничения, что и заданный вручную:
// отдельной ветки с досрочным возвратом больше нет — иначе вырожденное окно
// короче нижней ступени лестницы дало бы столбец шире самого окна.
//
// Возвращённый stepSec обязателен к выдаче наружу (step_seconds): иначе клиент
// вынужден угадывать ширину столбца по разнице соседних меток, а на ряде из
// одной точки угадать нечем.
func resolveChartStep(window, step time.Duration) (stepSec int64, buckets int) {
	if window <= 0 {
		return 1, 1
	}
	if step <= 0 {
		step = snapAutoStep(window)
	}
	if step > window {
		step = window
	}
	if n := int(window / step); n > maxChartBuckets {
		step = window / time.Duration(maxChartBuckets)
	}
	stepSec = max(int64(step.Seconds()), 1)
	buckets = max(int(int64(window.Seconds())/stepSec), 1)
	return stepSec, buckets
}
